"""Unattended installation of the router OS (Debian 13) from the provider ISO.

For every router HV Director remasters the provider's Debian 13 ISO with
xorriso and adds:

  /preseed.cfg           debian-installer answers (static management IP, root password, packages)
  /boot/grub/grub.cfg    one UEFI boot entry that starts the automated install
  /hvd/late.sh           post-install step: SSH keys, systemd-networkd, VRF, nftables
  /hvd/stage/*           complete router configuration rendered by routerconf

SSH host and client keys are generated by HV Director, so the router identity is
known before it boots and SSH connections verify the host key.
"""

from __future__ import annotations

import ipaddress
import os
import secrets
import shutil
import string
import subprocess
import tempfile
from dataclasses import dataclass, field

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from ..errors import AppError
from .routerconf import RouterSpec, render_all


