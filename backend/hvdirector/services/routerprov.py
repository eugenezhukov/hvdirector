@dataclass
class InstallSpec:
    hostname: str
    mgmt_ip: str
    mgmt_prefix: int
    mgmt_gateway: str | None
    dns: list[str]
    root_password: str
    authorized_keys: list[str]
    host_key_private: str
    host_key_public: str
    mirror_host: str = ""
    mirror_dir: str = "/debian"
    http_proxy: str = ""
    timezone: str = "Etc/UTC"
    extra_packages: list[str] = field(default_factory=list)

    @property
    def netmask(self) -> str:
        return str(ipaddress.IPv4Network(f"0.0.0.0/{self.mgmt_prefix}").netmask)


def _check_value(value: str, what: str) -> str:
    """Values are written into the kernel command line and preseed: keep them simple."""
    if any(c in value for c in " \t\n\"'\\$`;|&"):
        raise AppError("invalid_installer_value", f"Unsupported characters in {what}", field=what)
    return value


def render_preseed(s: InstallSpec) -> str:
    dns = " ".join(_check_value(d, "dns") for d in s.dns)
    lines = [
        "# HV Director: unattended installation of a virtual router (Debian 13)",
        "d-i debian-installer/locale string en_US.UTF-8",
        "d-i keyboard-configuration/xkb-keymap select us",
        "d-i hw-detect/load_firmware boolean false",
        "d-i netcfg/choose_interface select auto",
        "d-i netcfg/disable_autoconfig boolean true",
        f"d-i netcfg/get_ipaddress string {_check_value(s.mgmt_ip, 'mgmt_ip')}",
        f"d-i netcfg/get_netmask string {s.netmask}",
    ]
    if s.mgmt_gateway:
        lines.append(f"d-i netcfg/get_gateway string {_check_value(s.mgmt_gateway, 'gateway')}")
    else:
        lines += ["d-i netcfg/get_gateway string", "d-i netcfg/no_default_route boolean true"]
    lines += [
        f"d-i netcfg/get_nameservers string {dns}",
        "d-i netcfg/confirm_static boolean true",
        f"d-i netcfg/get_hostname string {_check_value(s.hostname, 'hostname')}",
        "d-i netcfg/get_domain string localdomain",
        f"d-i netcfg/hostname string {s.hostname}",
    ]
    if s.mirror_host:
        lines += [
            "d-i mirror/country string manual",
            f"d-i mirror/http/hostname string {_check_value(s.mirror_host, 'mirror_host')}",
            f"d-i mirror/http/directory string {_check_value(s.mirror_dir or '/debian', 'mirror_dir')}",
            f"d-i mirror/http/proxy string {_check_value(s.http_proxy, 'http_proxy')}",
            "d-i apt-setup/services-select multiselect security, updates",
        ]
    else:
        # Offline installation (DVD-1 ISO): no network mirror
        lines += [
            "d-i apt-setup/use_mirror boolean false",
            "d-i apt-setup/services-select multiselect",
        ]
    lines += [
        "d-i apt-setup/cdrom/set-first boolean false",
        "d-i apt-setup/disable-cdrom-entries boolean true",
        "d-i passwd/make-user boolean false",
        "d-i passwd/root-login boolean true",
        f"d-i passwd/root-password password {s.root_password}",
        f"d-i passwd/root-password-again password {s.root_password}",
        "d-i clock-setup/utc boolean true",
        f"d-i time/zone string {_check_value(s.timezone, 'timezone')}",
        "d-i clock-setup/ntp boolean false",
        "d-i partman-auto/disk string /dev/sda",
        "d-i partman-auto/method string regular",
        "d-i partman-auto/choose_recipe select atomic",
        "d-i partman-partitioning/choose_label select gpt",
        "d-i partman-partitioning/default_label string gpt",
        "d-i partman-partitioning/confirm_write_new_label boolean true",
        "d-i partman-efi/non_efi_system boolean true",
        "d-i partman/choose_partition select finish",
        "d-i partman/confirm boolean true",
        "d-i partman/confirm_nooverwrite boolean true",
        "d-i base-installer/install-recommends boolean false",
        "tasksel tasksel/first multiselect ssh-server",
        "d-i pkgsel/include string " + " ".join(["nftables", "openssh-server", "hyperv-daemons",
                                                 *s.extra_packages]),
        "d-i pkgsel/upgrade select none",
        "popularity-contest popularity-contest/participate boolean false",
        "d-i grub-installer/only_debian boolean true",
        "d-i grub-installer/with_other_os boolean false",
        "d-i grub-installer/bootdev string default",
        "d-i grub-installer/force-efi-extra-removable boolean true",
        "d-i cdrom-detect/eject boolean false",
        "d-i finish-install/reboot_in_progress note",
        "d-i preseed/late_command string sh /cdrom/hvd/late.sh",
        "",
    ]
    return "\n".join(lines)


def render_grub_cfg(s: InstallSpec) -> str:
    args = [
        "auto=true", "priority=critical", "preseed/file=/cdrom/preseed.cfg",
        "debian-installer/locale=en_US.UTF-8", "keyboard-configuration/xkb-keymap=us",
        "netcfg/choose_interface=auto", "netcfg/disable_autoconfig=true",
        f"netcfg/get_ipaddress={s.mgmt_ip}", f"netcfg/get_netmask={s.netmask}",
        "netcfg/confirm_static=true", f"netcfg/get_hostname={s.hostname}", "netcfg/get_domain=localdomain",
    ]
    if s.dns:  # the preseed file carries the full list
        args.append(f"netcfg/get_nameservers={s.dns[0]}")
    if s.mgmt_gateway:
        args.append(f"netcfg/get_gateway={s.mgmt_gateway}")
    cmdline = " ".join(args)
    return (
        "# HV Director automated router installation\n"
        "set default=0\n"
        "set timeout=3\n"
        "menuentry 'HV Director: automated router installation' {\n"
        f"    linux /install.amd/vmlinuz {cmdline} --- quiet\n"
        "    initrd /install.amd/initrd.gz\n"
        "}\n"
    )


LATE_SH = r"""#!/bin/sh
# HV Director: post-install configuration of the virtual router (runs inside debian-installer)
set -e
T=/target
H=/cdrom/hvd

install -d -m 0700 $T/root/.ssh
cp $H/authorized_keys $T/root/.ssh/authorized_keys
chmod 0600 $T/root/.ssh/authorized_keys

rm -f $T/etc/ssh/ssh_host_*_key $T/etc/ssh/ssh_host_*_key.pub
cp $H/ssh_host_ed25519_key $H/ssh_host_ed25519_key.pub $T/etc/ssh/
chmod 0600 $T/etc/ssh/ssh_host_ed25519_key
chmod 0644 $T/etc/ssh/ssh_host_ed25519_key.pub
install -d $T/etc/ssh/sshd_config.d
cp $H/sshd.conf $T/etc/ssh/sshd_config.d/90-hvd.conf

install -d $T/var/lib/hvd $T/etc/systemd/network
install -m 0755 $H/stage/hvd-apply $T/usr/local/sbin/hvd-apply
cp $H/stage/network/* $T/etc/systemd/network/
install -m 0644 $H/stage/nftables.conf $T/etc/nftables.conf
install -m 0644 $H/stage/sysctl.conf $T/etc/sysctl.d/90-hvd-router.conf

# systemd-networkd manages all interfaces (VRF, VLAN SVIs); ifupdown keeps only loopback
printf 'auto lo\niface lo inet loopback\n' > $T/etc/network/interfaces
in-target systemctl enable systemd-networkd.service
in-target systemctl enable nftables.service
in-target systemctl disable networking.service || true
echo "HV Director virtual router" > $T/etc/hvd-release
"""

SSHD_CONF = """# HV Director: key-only root access on the management interface
PermitRootLogin prohibit-password
PasswordAuthentication no
KbdInteractiveAuthentication no
HostKey /etc/ssh/ssh_host_ed25519_key
"""


def installer_files(router_spec: RouterSpec, s: InstallSpec) -> dict[str, str]:
    """ISO path -> content of every file added to the installer image."""
    files = {
        "/preseed.cfg": render_preseed(s),
        "/boot/grub/grub.cfg": render_grub_cfg(s),
        "/hvd/late.sh": LATE_SH,
        "/hvd/sshd.conf": SSHD_CONF,
        "/hvd/authorized_keys": "\n".join(k.strip() for k in s.authorized_keys if k.strip()) + "\n",
        "/hvd/ssh_host_ed25519_key": s.host_key_private,
        "/hvd/ssh_host_ed25519_key.pub": s.host_key_public.strip() + "\n",
    }
    for path, content in render_all(router_spec).items():
        files[f"/hvd/stage/{path}"] = content
    return files


