# ISO remastering (xorriso)
# ---------------------------------------------------------------------------


def xorriso_path() -> str:
    path = shutil.which("xorriso")
    if not path:
        raise AppError("xorriso_missing", "xorriso is not installed on the HV Director server (apt install xorriso)")
    return path


def remaster_iso(src_iso: str, dst_iso: str, files: dict[str, str], work_dir: str | None = None) -> None:
    """Copy src_iso to dst_iso adding/replacing files, keeping the BIOS/UEFI boot setup."""
    xorriso = xorriso_path()
    with tempfile.TemporaryDirectory(dir=work_dir, prefix="hvd-iso-") as td:
        args = [xorriso, "-abort_on", "FAILURE", "-indev", src_iso, "-outdev", dst_iso,
                "-boot_image", "any", "replay"]
        for i, (iso_path, content) in enumerate(sorted(files.items())):
            local = os.path.join(td, f"f{i}")
            with open(local, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(content)
            args += ["-map", local, iso_path]
        r = subprocess.run(args, capture_output=True, text=True, timeout=1800)
        if r.returncode != 0 or not os.path.exists(dst_iso):
            tail = (r.stderr or r.stdout).strip().splitlines()[-5:]
            raise AppError("iso_remaster_failed", "Cannot build the router installer ISO: " + " | ".join(tail))


def extract_file(iso: str, iso_path: str) -> str:
    """Read one file from an ISO (used by tests and diagnostics)."""
    xorriso = xorriso_path()
    with tempfile.TemporaryDirectory(prefix="hvd-iso-x-") as td:
        out = os.path.join(td, "file")
        subprocess.run([xorriso, "-osirrox", "on", "-indev", iso, "-extract", iso_path, out],
                       capture_output=True, check=True, timeout=300)
        with open(out, encoding="utf-8") as fh:
            return fh.read()
