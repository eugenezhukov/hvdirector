def generate_ed25519(comment: str = "") -> tuple[str, str]:
    """Return (OpenSSH private key, OpenSSH public key line)."""
    key = Ed25519PrivateKey.generate()
    private = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH,
                                serialization.NoEncryption()).decode()
    public = key.public_key().public_bytes(serialization.Encoding.OpenSSH,
                                           serialization.PublicFormat.OpenSSH).decode()
    return private, (public + (f" {comment}" if comment else ""))


def random_mac(taken: set[str] | None = None) -> str:
    """Static MAC in the Hyper-V OUI 00-15-5D (format accepted by Set-VMNetworkAdapter)."""
    taken = taken or set()
    while True:
        mac = "00155D" + secrets.token_hex(3).upper()
        if mac not in taken:
            return mac


def random_password(length: int = 20) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


