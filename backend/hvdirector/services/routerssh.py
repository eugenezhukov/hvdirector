"""Transport used to configure router VMs: SSH over the OOB management network.

The router host key is generated by HV Director and installed by the preseed,
so connections are made with RejectPolicy against that known key.
"""

from __future__ import annotations

import base64
import io
import logging
import os
import posixpath
import shlex
import time
from collections.abc import Callable
from dataclasses import dataclass, field

from ..config import get_config
from ..errors import AppError

log = logging.getLogger(__name__)


@dataclass
class RouterConn:
    host: str
    private_key: str = field(repr=False)
    host_key_pub: str
    port: int = 22
    username: str = "root"


class RouterTransport:
    name = "abstract"

    def wait_ready(self, conn: RouterConn, timeout_s: int, progress: Callable[[str], None] | None = None) -> None:
        raise NotImplementedError

    def apply(self, conn: RouterConn, files: dict[str, str]) -> str:
        raise NotImplementedError


class SshTransport(RouterTransport):
    name = "ssh"

    def _client(self, conn: RouterConn, timeout: int = 10):  # noqa: ANN202
        import paramiko

        client = paramiko.SSHClient()
        parts = conn.host_key_pub.split()
        if len(parts) < 2 or parts[0] != "ssh-ed25519":
            raise AppError("router_hostkey_invalid", "Router host key is missing or invalid")
        hostkey = paramiko.Ed25519Key(data=base64.b64decode(parts[1]))
        entry = conn.host if conn.port == 22 else f"[{conn.host}]:{conn.port}"
        client.get_host_keys().add(entry, "ssh-ed25519", hostkey)
        client.set_missing_host_key_policy(paramiko.RejectPolicy())
        pkey = paramiko.Ed25519Key.from_private_key(io.StringIO(conn.private_key))
        client.connect(conn.host, port=conn.port, username=conn.username, pkey=pkey, timeout=timeout,
                       banner_timeout=timeout, auth_timeout=timeout, allow_agent=False, look_for_keys=False)
        return client

    def _run(self, client, command: str, timeout: int = 300) -> tuple[int, str]:  # noqa: ANN001
        _, stdout, stderr = client.exec_command(command, timeout=timeout)
        out = stdout.read().decode("utf-8", "replace")
        err = stderr.read().decode("utf-8", "replace")
        code = stdout.channel.recv_exit_status()
        return code, (out + err).strip()

    def wait_ready(self, conn: RouterConn, timeout_s: int, progress: Callable[[str], None] | None = None) -> None:
        deadline = time.monotonic() + timeout_s
        started = time.monotonic()
        last_error = ""
        while time.monotonic() < deadline:
            try:
                client = self._client(conn)
                try:
                    code, out = self._run(client, "test -x /usr/local/sbin/hvd-apply && cat /etc/hvd-release", 30)
                finally:
                    client.close()
                if code == 0:
                    return
                last_error = out
            except Exception as exc:  # noqa: BLE001 - router is still installing
                last_error = f"{type(exc).__name__}: {exc}"
            if progress:
                progress(f"installing OS, {int((time.monotonic() - started) / 60)} min")
            time.sleep(15)
        raise AppError("router_install_timeout",
                       f"Router did not become reachable over SSH at {conn.host}: {last_error}")

    def apply(self, conn: RouterConn, files: dict[str, str]) -> str:
        stage = f"/var/lib/hvd/stage-{int(time.time())}"
        try:
            client = self._client(conn, timeout=15)
        except Exception as exc:  # noqa: BLE001
            raise AppError("router_unreachable", f"Cannot connect to router {conn.host} over SSH: {exc}") from exc
        try:
            dirs = sorted({posixpath.dirname(posixpath.join(stage, p)) for p in files})
            code, out = self._run(client, "mkdir -p " + " ".join(shlex.quote(d) for d in dirs))
            if code != 0:
                raise AppError("router_apply_failed", f"Cannot create staging directory: {out}")
            sftp = client.open_sftp()
            try:
                for path, content in files.items():
                    with sftp.open(posixpath.join(stage, path), "w") as fh:
                        fh.write(content.encode("utf-8"))
            finally:
                sftp.close()
            cmd = (f"install -m 0755 {stage}/hvd-apply /usr/local/sbin/hvd-apply && "
                   f"/usr/local/sbin/hvd-apply {stage}; rc=$?; rm -rf {stage}; exit $rc")
            code, out = self._run(client, cmd)
            if code != 0 or "HVD-APPLY-OK" not in out:
                raise AppError("router_apply_failed", f"Router rejected the configuration: {out[-1500:]}")
            return out
        finally:
            client.close()


class FakeTransport(RouterTransport):
    """Simulated router (HVD_HYPERV_DRIVER=fake): stores pushed files locally."""

    name = "fake"

    def __init__(self, base_dir: str) -> None:
        self.base_dir = base_dir

    def wait_ready(self, conn: RouterConn, timeout_s: int, progress: Callable[[str], None] | None = None) -> None:
        if progress:
            progress("installing OS (simulated)")
        time.sleep(float(os.environ.get("HVD_FAKE_DELAY", "0.5")))

    def apply(self, conn: RouterConn, files: dict[str, str]) -> str:
        root = os.path.join(self.base_dir, conn.host)
        for path, content in files.items():
            dest = os.path.join(root, path)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "w", encoding="utf-8") as fh:
                fh.write(content)
        return "HVD-APPLY-OK (simulated)"


def get_transport() -> RouterTransport:
    cfg = get_config()
    if cfg.hyperv_driver == "fake":
        return FakeTransport(os.path.join(os.path.dirname(os.path.abspath(cfg.fake_state_file)), "fake-routers"))
    return SshTransport()
